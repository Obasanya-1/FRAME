import assert from 'node:assert/strict';
import {findImageShapeDropTarget,pointInsideShape} from '../packages/editor/src/shapeDropTarget.js';
const rect={id:'rect',type:'shape',shape:'rectangle',x:100,y:100,w:150,h:150,z:2};
const other={id:'other',type:'shape',shape:'rounded',radius:10,x:260,y:100,w:120,h:120,z:10};
const image={id:'photo',type:'image',x:90,y:90,w:270,h:230,z:20};
const layers=[rect,other,image];
assert.equal(findImageShapeDropTarget(layers,image,{x:110,y:120})?.id,'rect');
assert.equal(findImageShapeDropTarget(layers,image,{x:280,y:120})?.id,'other');
assert.equal(findImageShapeDropTarget(layers,image,{x:110,y:120},new Set(['rect'])),null);
assert.equal(findImageShapeDropTarget(layers,image,{x:990,y:990}),null,'overlap alone cannot request a fill');
assert.equal(findImageShapeDropTarget(layers,image,{x:255,y:245}),null,'photo center cannot request a fill');
assert.equal(findImageShapeDropTarget(layers,{...image,type:'text'},{x:110,y:120}),null);
assert.equal(findImageShapeDropTarget(layers,image,null),null);
assert.equal(pointInsideShape({type:'shape',shape:'ellipse',x:0,y:0,w:100,h:100},{x:2,y:2}),false,'ellipse corners are not drop targets');
assert.equal(pointInsideShape({type:'shape',shape:'ellipse',x:0,y:0,w:100,h:100},{x:50,y:50}),true);
assert.equal(pointInsideShape({type:'shape',shape:'triangle',x:0,y:0,w:100,h:100},{x:5,y:5}),false);
assert.equal(pointInsideShape({type:'shape',shape:'triangle',x:0,y:0,w:100,h:100},{x:50,y:60}),true);
assert.equal(pointInsideShape({...other,x:0,y:0},{x:1,y:1}),false,'rounded corners do not accept drops');
console.log('FRAME Mobile 08J intentional shape hit tests passed');
