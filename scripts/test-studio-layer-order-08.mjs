import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
import {moveLayerInStack} from '../packages/editor/src/layerOrdering.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const order=items=>[...items].sort((a,b)=>(b.z||0)-(a.z||0)).map(item=>item.id);
const original=[{id:'A',z:3,type:'image',src:'data:image/png;base64,a',x:0,w:60},{id:'B',z:2,type:'shape',shape:'star',groupId:'g'},{id:'C',z:1,type:'text',groupId:'g'}];
const up=moveLayerInStack(original,'C','B');
assert.deepEqual(order(up),['A','C','B'],'moving above puts item immediately ahead of target');
assert.deepEqual(original.map(l=>l.z),[3,2,1],'original data remains untouched, compatible with Undo snapshots');
assert.equal(up[2].groupId,'g','group metadata must survive reordering');
const down=moveLayerInStack(original,'A','C',true);
assert.deepEqual(order(down),['B','C','A'],'moving below last item sends it to back');
assert.deepEqual(original.map(l=>l.z),[3,2,1],'reorder must not mutate original z indices');
assert.equal(down.find(l=>l.id==='A').src,original[0].src,'full image content preserved');
assert.equal(moveLayerInStack(original,'A','A'),original,'dragging onto itself is a no-op');
assert.equal(moveLayerInStack(original,'A','B',false),original,'already-adjacent before target is a no-op');
assert.equal(moveLayerInStack(original,'C','missing'),original,'invalid targets are no-ops');
assert.equal(moveLayerInStack(original,'missing','C'),original,'invalid sources are no-ops');
const saved=JSON.parse(JSON.stringify({pages:1,layers:down}));
assert.deepEqual(order(saved.layers),['B','C','A'],'order survives .frame JSON round trip');
const originalSnapshot=JSON.parse(JSON.stringify({pages:1,layers:original}));
assert.deepEqual(order(originalSnapshot.layers),['A','B','C'],'undo snapshot preserves original stacking order');
const sameZ=[{id:'a',z:0},{id:'b',z:0},{id:'c',z:0}];
assert.deepEqual(order(moveLayerInStack(sameZ,'c','a')),['c','a','b'],'duplicate z values are normalized when reordered');
const jsx=readFileSync(resolve(root,'packages/editor/src/main.jsx'),'utf8');
const css=readFileSync(resolve(root,'packages/editor/src/styles.css'),'utf8');
assert.match(jsx,/onPointerDown=\{e=>beginPointerReorder\(e,l\.id\)\}/,'desktop layer row uses pointer gesture');
assert.match(jsx,/draggable=\{IS_MOBILE\}/,'desktop no longer relies on native button drag');
assert.match(jsx,/onClick=\{\(\)=>moveSelected\(-1\)\}/,'up button attached');
assert.match(jsx,/onClick=\{\(\)=>moveSelected\(1\)\}/,'down button attached');
assert.match(css,/\.layer-reorder-actions button:disabled/,'unavailable direction controls disabled');
console.log('Studio Parity 08: reorder, no-op, image and group preservation, persistence, undo snapshot, and inspector controls passed.');
