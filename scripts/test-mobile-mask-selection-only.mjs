import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolveMaskedImageId,isMaskedImageTap} from '../packages/editor/src/maskTap.mjs';
const src=readFileSync(new URL('../packages/editor/src/main.jsx',import.meta.url),'utf8');
const css=readFileSync(new URL('../apps/mobile/src/mobile.css',import.meta.url),'utf8');
const shape={id:'mask',type:'shape'};
const photo={id:'photo',type:'image',maskShapeId:'mask'};
assert.equal(resolveMaskedImageId([shape,photo],shape),'photo');
assert.equal(resolveMaskedImageId([shape,photo],photo),'photo');
assert.ok(isMaskedImageTap({distance:0,moved:false}));
assert.ok(!isMaskedImageTap({distance:20,moved:true}));
assert.ok(!isMaskedImageTap({distance:0,holdTriggered:true}));
assert.ok(!isMaskedImageTap({distance:0,gestureBlocked:true}));
const expect=(part,msg)=>assert.ok(src.includes(part),msg);
expect('mobile-mask-selection-frame', 'render an ordinary selection frame');
expect("onPointerDown={e=>startDrag(e,active)}", 'selected frame captures touches and routes to the layer drag controller');
expect("!e.target.closest('.layer,.mobile-mask-crop-target,.mobile-mask-selection-frame')", 'frame touches do not start workspace panning');
expect("e.target.closest('.layer,.mobile-mask-selection-frame')", 'frame touches must not clear selection on the workspace');
expect('mobileCanvasPan.current=null;', 'masked selection cancels stale workspace panning');
expect('if(tappedMask){', 'mask tap is handled without opening inspector');
assert.doesNotMatch(src,/if\(tappedMask\)\s*\{[^}]*setMobileEditOpen\(true\)/,'tap must not open inspector');
assert.match(css,/\.mobile-mask-selection-frame\s*\{[^}]*pointer-events:auto;touch-action:none;/,'the selection frame must be a real hit target, not click-through');
expect('onPointerDown={e=>startResize(e,mask,handle)}', 'normal selection handles remain functional');
console.log('08P: masked image tap selects only, outline catches touches, no workspace pan or inspector popup.');
